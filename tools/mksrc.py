#!/usr/bin/env python3
"""Turn BREAKOUT.ACC (Alcyon C, 1986) into vasm source that rebuilds it.

usage: mksrc.py ORIGINAL OUT.s [--fix]

Every instruction becomes raw dc.w words with objdump's disassembly as a
remark; every relocated longword becomes "dc.l label", so code can be added
and the program re-linked. Labels come from the DRI symbol table in the
binary, the rest are called L_xxxx (original address).

With --fix the instructions listed in tools/patches.py are replaced by the
given lines and src/fix.s is included behind the original code.
"""
import re, struct, subprocess, sys, os

OBJDUMP = '/opt/cross-mint/bin/m68k-atari-mint-objdump'
here = os.path.dirname(os.path.abspath(__file__))

src, out = sys.argv[1], sys.argv[2]
fix = '--fix' in sys.argv
d = open(src, 'rb').read()
_, tlen, dlen, blen, slen = struct.unpack('>HIIII', d[:18])
img = d[28:28 + tlen + dlen]

# DRI symbol table
names = {}
o = 28 + tlen + dlen
for i in range(slen // 14):
    e = d[o + i * 14:o + i * 14 + 14]
    names.setdefault(struct.unpack('>I', e[10:])[0], []).append(
        e[:8].rstrip(b'\0').decode())

# relocation table
r = 28 + tlen + dlen + slen
a = struct.unpack('>I', d[r:r + 4])[0]
relocs = set()
if a:
    relocs.add(a)
    p = r + 4
    while d[p]:
        a += 254 if d[p] == 1 else d[p]
        if d[p] != 1:
            relocs.add(a)
        p += 1
lval = lambda x: struct.unpack('>I', img[x:x + 4])[0]
targets = {lval(x) for x in relocs} | set(names)

# instruction boundaries from objdump
open('/tmp/_bo.bin', 'wb').write(img[:tlen])
lst = subprocess.run([OBJDUMP, '-D', '-b', 'binary', '-m', 'm68k',
                      '/tmp/_bo.bin'], capture_output=True, text=True).stdout
ins = []
for l in lst.splitlines():
    m = re.match(r'\s+([0-9a-f]+):\t([0-9a-f ]+)\t?(.*)', l)
    if m:
        a = int(m.group(1), 16)
        n = len(m.group(2).replace(' ', '')) // 2
        if not m.group(3).strip() and ins:       # objdump continuation line
            ins[-1][1] += n
            continue
        ins.append([a, n, m.group(3).strip()])
starts = [i[0] for i in ins]

def label(v):
    if v in names:
        return names[v][0]
    return 'L_%04x' % v

# where a label is placed: text targets at instruction starts, data/bss
# targets at even addresses
def place(v):
    if v < tlen:
        return max(s for s in starts if s <= v)
    return v & ~1

placed = {place(v) for v in targets}
def ref(v):
    p = place(v)
    return label(p) + ('+%d' % (v - p) if v != p else '')

def pretty(t):
    def rep(mm):
        v = int(mm.group(1)) if mm.group(1) else int(mm.group(2), 16)
        return ('#' if mm.group(0)[0] == '#' else '') + ref(v) if v >= 0x100 and v < tlen + dlen + blen + 16 else mm.group(0)
    return re.sub(r'(?<![\w@(])#?(?:(\d{3,5})|0x([0-9a-f]{3,5}))\b', rep, t)

def words(a, n):
    """dc lines for bytes a..a+n, relocated longwords as labels"""
    out, x, buf = [], a, []
    while x < a + n:
        if x in relocs:
            if buf:
                out.append('dc.w ' + ','.join(buf)); buf = []
            out.append('dc.l ' + ref(lval(x))); x += 4
        else:
            buf.append('$%04x' % struct.unpack('>H', img[x:x + 2])[0]); x += 2
    if buf:
        out.append('dc.w ' + ','.join(buf))
    return out

patches = {}
if fix:
    sys.path.insert(0, here)
    from patches import PATCHES
    patches = PATCHES

L = ['; generated by tools/mksrc.py from BREAKOUT.ACC - do not edit',
     '; (Alcyon C 1986; remarks are objdump disassembly)', '',
     '\tsection text']
def labels_at(a):
    if a in names:
        for n in names[a]:
            L.append(n + ':')
    elif a in placed:
        L.append(label(a) + ':')

skip_to = 0
for a, n, t in ins:
    if a < skip_to:
        if a in placed:
            sys.exit('label %x inside a patch' % a)
        continue
    labels_at(a)
    if a in patches:
        length, code = patches[a]
        if a + length not in starts:
            sys.exit('patch at %x does not end on an instruction' % a)
        L.append('; --- patched %04x-%04x' % (a, a + length))
        L += ['\t' + c for c in code]
        skip_to = a + length
        continue
    w = words(a, n)
    L.append('\t' + w[0] + '\t; ' + pretty(t))
    L += ['\t' + x for x in w[1:]]
if fix:
    L += ['', '\tinclude "fix.s"', '', '\tsection text']

L += ['', '\tsection data']
a = tlen
while a < tlen + dlen:
    labels_at(a)
    n = 4 if a in relocs else 2
    L += ['\t' + x for x in words(a, n)]
    a += n

L += ['', '\tsection bss']
pts = sorted(p for p in placed | set(names) if p >= tlen + dlen) + [tlen + dlen + blen]
a = tlen + dlen
for p in pts:
    if p > a:
        L.append('\tds.b %d' % (p - a)); a = p
    if p < tlen + dlen + blen:
        labels_at(p)
open(out, 'w').write('\n'.join(L) + '\n')
